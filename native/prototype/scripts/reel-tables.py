"""Generate MOSS's own normalized fractional-delay and sine lookup tables.

Only Python's standard library is required. No third-party DSP implementation.
12-tap Kaiser beta=5, 256 fractional phases with coefficient interpolation.
"""
from pathlib import Path
import math


def i0(x):
    value = term = 1.0
    for k in range(1, 40):
        term *= (x / (2 * k)) ** 2
        value += term
    return value


def number(x):
    if abs(x) < 1e-14:
        return '0.0f'
    return f'{x:.9e}f'


lines = ['// Generated by scripts/reel-tables.py; do not edit.', '#pragma once',
         'namespace moss {', 'inline constexpr float ReelSinc[257][12] = {']
for phase in range(257):
    weights = []
    for k in range(-5, 7):
        x = k - phase / 256
        sinc = math.sin(math.pi * x) / (math.pi * x) if x else 1
        weights.append(sinc * i0(5 * math.sqrt(max(0, 1 - (x / 6) ** 2))) / i0(5))
    total = sum(weights)
    # Oldest-to-newest samples make stereo vector loads contiguous on ARM.
    lines.append('  {' + ','.join(number(x / total) for x in reversed(weights)) + '},')
lines += ['};', 'inline constexpr float ReelSine[257] = {']
for k in range(0, 257, 8):
    lines.append('  ' + ','.join(number(math.sin(2 * math.pi * j / 256))
                                for j in range(k, min(k + 8, 257))) + ',')
lines += ['};', '} // namespace moss', '']
path = Path(__file__).resolve().parents[1] / 'src/reel_tables.h'
path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(path)
